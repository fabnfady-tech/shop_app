def seed_database():
    conn = sqlite3.connect("shop.db")
    cursor = conn.cursor()
    
    cursor.execute("PRAGMA table_info(products)")
    existing_columns = [col[1] for col in cursor.fetchall()]

    qty_column = "quantity"
    if "stock" in existing_columns:
        qty_column = "stock"
    elif "qty" in existing_columns:
        qty_column = "qty"

    if "unit" not in existing_columns:
        try:
            cursor.execute("ALTER TABLE products ADD COLUMN unit TEXT DEFAULT 'قطعة'")
        except:
            pass

    cursor.execute("DELETE FROM products;")
    try:
        cursor.execute("DELETE FROM sqlite_sequence WHERE name='products';")
    except:
        pass

    insert_sql = f"INSERT INTO products (name, price, category, unit, {qty_column}) VALUES (?, ?, ?, ?, ?)"
    
    count = 0
    for name, price, category, unit in products_data:
        cursor.execute(insert_sql, (name, price, category, unit, 50.0))
        count += 1

    conn.commit()
    conn.close()
    print(f"تم تعديل التصنيفات بنجاح! تم إدخال {count} منتج.")

if __name__ == "__main__":
    seed_database()