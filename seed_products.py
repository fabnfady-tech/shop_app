def seed_database():
    conn = sqlite3.connect(DB_PATH)
    cursor = conn.cursor()
    
    # فحص الأوردة والعمود المتاح للكمية
    cursor.execute("PRAGMA table_info(products)")
    existing_columns = [col[1] for col in cursor.fetchall()]

    qty_column = "stock"
    if "stock" not in existing_columns:
        if "quantity" in existing_columns:
            qty_column = "quantity"
        elif "qty" in existing_columns:
            qty_column = "qty"
        else:
            try:
                cursor.execute("ALTER TABLE products ADD COLUMN stock REAL DEFAULT 0")
            except Exception:
                pass

    if "unit" not in existing_columns:
        try:
            cursor.execute("ALTER TABLE products ADD COLUMN unit TEXT DEFAULT 'قطعة'")
        except Exception:
            pass

    if "category" not in existing_columns:
        try:
            cursor.execute("ALTER TABLE products ADD COLUMN category TEXT DEFAULT 'عام'")
        except Exception:
            pass

    count = 0
    for name, price, category, unit, stock in products_data:
        cursor.execute("SELECT id FROM products WHERE name = ?", (name,))
        if not cursor.fetchone():
            cursor.execute(
                f"INSERT INTO products (name, price, category, unit, {qty_column}) VALUES (?, ?, ?, ?, ?)",
                (name, price, category, unit, stock)
            )
            count += 1

    conn.commit()
    conn.close()
    print(f"تم تحديث قاعدة البيانات بنجاح! تم إضافة {count} منتج جديد بالأسعار والكميات المحددة.")

if __name__ == "__main__":
    seed_database()